CREATE TABLE `hos`.`lab_order_service` (
  `lab_order_service_id` int(11) NOT NULL,
  `lab_order_number` int(11) NOT NULL DEFAULT 0,
  `lab_order_type` varchar(15) NOT NULL DEFAULT '',
  `lab_code` int(11) NOT NULL DEFAULT 0,
  `lab_name` varchar(250) DEFAULT NULL,
  `price` double(15,3) DEFAULT NULL,
  `opi_guid` varchar(38) DEFAULT NULL,
  `icode` varchar(7) DEFAULT NULL,
  `vn` varchar(13) DEFAULT NULL,
  `department` char(3) DEFAULT NULL,
  `lab_order_service_guid` varchar(38) DEFAULT NULL,
  `hos_guid` varchar(38) DEFAULT NULL,
  `ref_order_number` int(11) DEFAULT NULL,
  `specimen_code` int(11) DEFAULT NULL,
  `est_wait_minute` int(11) DEFAULT NULL,
  `update_flag` int(11) DEFAULT NULL,
  PRIMARY KEY (`lab_order_service_id`),
  KEY `ix_lab_order_number` (`lab_order_number`),
  KEY `ix_opi_guid` (`opi_guid`),
  KEY `ix_vn` (`vn`),
  KEY `ix_lab_order_service_guid` (`lab_order_service_guid`),
  KEY `ix_ref_no` (`ref_order_number`),
  KEY `ix_order_type_code` (`lab_order_number`,`lab_order_type`,`lab_code`),
  KEY `ix_order_type_code_index` (`lab_code`,`lab_order_type`,`lab_order_number`)
) ENGINE=InnoDB DEFAULT CHARSET=tis620 COLLATE=tis620_thai_ci