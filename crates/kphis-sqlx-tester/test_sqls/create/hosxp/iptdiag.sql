CREATE TABLE `hos`.`iptdiag` (
  `ipt_diag_id` int(11) NOT NULL DEFAULT 0,
  `an` varchar(9) DEFAULT NULL,
  `diagtype` char(2) DEFAULT NULL,
  `doctor` varchar(7) DEFAULT NULL,
  `icd10` varchar(9) DEFAULT NULL,
  `hos_guid` varchar(38) DEFAULT NULL,
  `staff` varchar(25) DEFAULT NULL,
  `hn` varchar(9) DEFAULT NULL,
  `entry_datetime` datetime DEFAULT NULL,
  `modify_datetime` datetime DEFAULT NULL,
  `diagnosis_note` varchar(250) DEFAULT NULL,
  `dx_guid` varchar(38) DEFAULT NULL,
  `diag_no` int(11) DEFAULT NULL,
  `icd11` varchar(10) DEFAULT NULL,
  `diag_lock_status` char(1) DEFAULT NULL,
  `diag_lock_staff` varchar(50) DEFAULT NULL,
  `diag_lock_datetime` datetime DEFAULT NULL,
  PRIMARY KEY (`ipt_diag_id`),
  UNIQUE KEY `ix_unique` (`an`,`icd10`),
  UNIQUE KEY `ix_unique_index` (`an`,`icd10`),
  KEY `ix_an` (`an`),
  KEY `ix_doctor` (`doctor`),
  KEY `ix_hos_guid` (`hos_guid`),
  KEY `ix_dx_guid` (`dx_guid`),
  KEY `ix_an_dxtype` (`an`,`diagtype`),
  KEY `ix_an_dxtype_index` (`an`,`diagtype`)
) ENGINE=InnoDB DEFAULT CHARSET=tis620 COLLATE=tis620_thai_ci