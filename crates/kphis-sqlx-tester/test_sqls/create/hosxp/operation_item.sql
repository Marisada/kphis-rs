CREATE TABLE `hos`.`operation_item` (
  `operation_item_id` int(11) NOT NULL DEFAULT 0,
  `name` varchar(100) DEFAULT NULL,
  `icode` varchar(7) DEFAULT NULL,
  `price` double(15,3) DEFAULT NULL,
  `price2` double(15,3) DEFAULT NULL,
  `price3` double(15,3) DEFAULT NULL,
  `price_ipd` double(15,3) DEFAULT NULL,
  `price_ipd2` double(15,3) DEFAULT NULL,
  `price_ipd3` double(15,3) DEFAULT NULL,
  `icd9` varchar(7) DEFAULT NULL,
  `operation_group_id` int(11) DEFAULT NULL,
  `operation_item_type_id` int(11) DEFAULT NULL,
  `hos_guid` varchar(38) DEFAULT NULL,
  `active_status` char(1) DEFAULT NULL,
  `keyword` varchar(150) DEFAULT NULL,
  PRIMARY KEY (`operation_item_id`),
  KEY `icode` (`icode`),
  KEY `name` (`name`),
  KEY `ix_hos_guid` (`hos_guid`),
  KEY `ix_name_active_status` (`name`,`active_status`),
  KEY `ix_name_active_status_index` (`active_status`,`name`),
  KEY `ix_keyword` (`keyword`),
  KEY `ix_name_keyword` (`name`,`keyword`),
  KEY `ix_name_keyword_index` (`keyword`,`name`)
) ENGINE=InnoDB DEFAULT CHARSET=tis620 COLLATE=tis620_thai_ci