CREATE TABLE `hos`.`drug_interaction` (
  `drug_interaction_id` int(11) NOT NULL DEFAULT 0,
  `drugname1` varchar(250) NOT NULL DEFAULT '',
  `drugname2` varchar(250) NOT NULL DEFAULT '',
  `drug_interaction_type` int(11) NOT NULL DEFAULT 0,
  `note` text DEFAULT NULL,
  `severity` int(11) DEFAULT NULL,
  `show_doctor` char(1) DEFAULT NULL,
  `print_sticker` char(1) DEFAULT NULL,
  `not_allow` char(1) DEFAULT NULL,
  `check_old_prescription` char(1) DEFAULT NULL,
  `hos_guid` char(38) DEFAULT NULL,
  `check_old_interval` int(11) DEFAULT NULL,
  `tmt_substance_code1` varchar(6) DEFAULT NULL,
  `tmt_substance_code2` varchar(6) DEFAULT NULL,
  PRIMARY KEY (`drug_interaction_id`),
  KEY `drugname2` (`drugname2`),
  KEY `drugname1` (`drugname1`),
  KEY `drugname12` (`drugname1`,`drugname2`),
  KEY `ix_hos_guid` (`hos_guid`),
  KEY `ix_drugname12` (`drugname1`,`drugname2`),
  KEY `ix_drugname12_index` (`drugname1`,`drugname2`)
) ENGINE=InnoDB DEFAULT CHARSET=tis620 COLLATE=tis620_thai_ci