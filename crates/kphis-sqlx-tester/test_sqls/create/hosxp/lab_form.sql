CREATE TABLE `hos`.`lab_form` (
  `form_name` varchar(250) NOT NULL,
  `lab_items_code` int(11) DEFAULT NULL,
  `form_position_left` int(11) DEFAULT NULL,
  `form_position_top` int(11) DEFAULT NULL,
  `tab_order` tinyint(4) DEFAULT NULL,
  `form_position_width` int(11) DEFAULT NULL,
  `component_name` varchar(200) NOT NULL,
  `parent_name` varchar(200) DEFAULT NULL,
  `component_type` varchar(25) DEFAULT NULL,
  `component_caption` varchar(250) DEFAULT NULL,
  `checked` char(1) DEFAULT NULL,
  `form_position_height` int(11) DEFAULT NULL,
  `font_name` varchar(50) DEFAULT NULL,
  `font_size` int(11) DEFAULT NULL,
  `font_color` int(11) DEFAULT NULL,
  `specimen_code` int(11) DEFAULT NULL,
  `hos_guid` varchar(38) DEFAULT NULL,
  PRIMARY KEY (`form_name`,`component_name`),
  KEY `form_name` (`form_name`),
  KEY `form_name_lab_items_code` (`form_name`,`lab_items_code`),
  KEY `lab_items_code` (`lab_items_code`),
  KEY `ix_hos_guid` (`hos_guid`),
  KEY `ix_form_name_lab_items_code` (`form_name`,`lab_items_code`),
  KEY `ix_form_name_lab_items_code_index` (`form_name`,`lab_items_code`)
) ENGINE=InnoDB DEFAULT CHARSET=tis620 COLLATE=tis620_thai_ci