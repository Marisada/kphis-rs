CREATE TABLE `hos`.`sp_use` (
  `sp_use` varchar(7) NOT NULL,
  `sp_name` varchar(150) DEFAULT NULL,
  `name1` varchar(150) DEFAULT NULL,
  `name2` varchar(150) DEFAULT NULL,
  `name3` varchar(150) DEFAULT NULL,
  `user` varchar(15) DEFAULT NULL,
  `sp_use_guid` varchar(38) DEFAULT NULL,
  `oldcode` varchar(20) DEFAULT NULL,
  `hos_guid` varchar(38) DEFAULT NULL,
  `hos_guid_ext` varchar(64) DEFAULT NULL,
  PRIMARY KEY (`sp_use`),
  KEY `name1_name3_name2` (`name1`,`name3`,`name2`),
  KEY `sp_name` (`sp_name`),
  KEY `user` (`user`),
  KEY `ix_oldcode` (`oldcode`),
  KEY `ix_sp_use_guid` (`sp_use_guid`),
  KEY `ix_hos_guid_ext` (`hos_guid_ext`),
  KEY `ix_name1_name3_name2` (`name1`,`name2`,`name3`),
  KEY `ix_name1_name3_name2_index` (`name1`,`name2`,`name3`)
) ENGINE=InnoDB DEFAULT CHARSET=tis620 COLLATE=tis620_thai_ci