CREATE TABLE `hos`.`thaiaddress` (
  `addressid` varchar(6) NOT NULL DEFAULT '',
  `name` varchar(50) DEFAULT NULL,
  `engname` varchar(100) DEFAULT NULL,
  `chwpart` char(2) DEFAULT NULL,
  `amppart` char(2) DEFAULT NULL,
  `tmbpart` char(2) DEFAULT NULL,
  `codetype` char(1) DEFAULT NULL,
  `pocode` varchar(5) DEFAULT NULL,
  `full_name` varchar(250) DEFAULT NULL,
  `hos_guid` varchar(38) DEFAULT NULL,
  `hos_guid_ext` varchar(64) DEFAULT NULL,
  PRIMARY KEY (`addressid`),
  KEY `amppart` (`amppart`),
  KEY `chwpart` (`chwpart`),
  KEY `codetype` (`codetype`),
  KEY `name` (`name`),
  KEY `tmbpart` (`tmbpart`),
  KEY `ix_hos_guid` (`hos_guid`),
  KEY `ix_hos_guid_ext` (`hos_guid_ext`),
  KEY `ix_chwpart_amp_codetype` (`chwpart`,`amppart`,`codetype`),
  KEY `ix_chwpart_amp_tmb_codetype` (`chwpart`,`amppart`,`tmbpart`,`codetype`),
  KEY `ix_chwpart_codetype` (`chwpart`,`codetype`),
  KEY `ix_chwpart_amp_codetype_index` (`amppart`,`chwpart`,`codetype`),
  KEY `ix_chwpart_codetype_index` (`codetype`,`chwpart`),
  KEY `ix_chwpart_amp_tmb_codetype_index` (`amppart`,`chwpart`,`codetype`,`tmbpart`)
) ENGINE=InnoDB DEFAULT CHARSET=tis620 COLLATE=tis620_thai_ci