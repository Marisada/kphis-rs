CREATE TABLE `hos`.`lab_order` (
  `lab_order_number` int(11) NOT NULL,
  `lab_items_code` int(11) NOT NULL,
  `lab_order_result` varchar(250) DEFAULT NULL,
  `lab_order_remark` varchar(250) DEFAULT NULL,
  `staff` varchar(50) DEFAULT NULL,
  `confirm` char(1) DEFAULT NULL,
  `lab_items_name_ref` varchar(250) DEFAULT NULL,
  `lab_items_normal_value_ref` varchar(150) DEFAULT NULL,
  `specimen_code` int(11) DEFAULT NULL,
  `lab_items_sub_group_code` int(11) DEFAULT NULL,
  `order_type` char(1) DEFAULT NULL,
  `item_cost` double(15,3) DEFAULT NULL,
  `hos_guid` varchar(38) DEFAULT NULL,
  `staff_lock_result` char(1) DEFAULT NULL,
  `laborder_date` date DEFAULT NULL,
  `abnormal_result` char(1) DEFAULT NULL,
  `hos_guid_ext` varchar(64) DEFAULT NULL,
  `check_key` varchar(50) DEFAULT NULL,
  `lab_result_status` int(11) DEFAULT NULL,
  `update_datetime` datetime DEFAULT NULL,
  `lab_hist_compare_type_id` int(11) DEFAULT NULL,
  `printed` char(1) DEFAULT NULL,
  `printed_datetime` datetime DEFAULT NULL,
  `critical_result` char(1) DEFAULT NULL,
  `check_key_a` varchar(50) DEFAULT NULL,
  `send_notify` char(1) DEFAULT NULL,
  PRIMARY KEY (`lab_order_number`,`lab_items_code`),
  KEY `lab_order_number` (`lab_order_number`),
  KEY `ix_hos_guid` (`hos_guid`),
  KEY `ix_lab_items_code` (`lab_items_code`),
  KEY `ix_laborder_date` (`laborder_date`),
  KEY `ix_hos_guid_ext` (`hos_guid_ext`)
) ENGINE=InnoDB DEFAULT CHARSET=tis620 COLLATE=tis620_thai_ci